// Fresh-clone friendliness: if no local.properties exists, probe the usual
// SDK locations for one that actually has the compileSdk platform and write
// it in (git-ignored). An existing local.properties or a serving ANDROID_HOME
// is always left untouched.
val localProperties = File(rootDir, "local.properties")
if (!localProperties.exists()) {
    val compileSdkDir = "android-35" // keep in sync with app/build.gradle.kts compileSdk
    val sdk = listOfNotNull(
        System.getenv("ANDROID_HOME"),
        System.getenv("ANDROID_SDK_ROOT"),
        System.getProperty("user.home")?.plus("/Library/Android/sdk"),
        System.getProperty("user.home")?.plus("/Android/Sdk"),
    ).firstOrNull { File(it, "platforms/$compileSdkDir").isDirectory }
    if (sdk != null) {
        runCatching {
            localProperties.writeText(
                "# generated by settings.gradle.kts — edit or delete at will (git-ignored)\n" +
                    "sdk.dir=$sdk\n",
            )
            logger.lifecycle("ReelGuard: provisioned local.properties (sdk.dir=$sdk)")
        }
    }
}

